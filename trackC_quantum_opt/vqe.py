"""trackC_quantum_opt/vqe.py
-------------------------
Variational Quantum Eigensolver (VQE) utilities:
- Physical spin Hamiltonians (Transverse-Field Ising chain, Heisenberg chain)
- Hardware-efficient variational ansatz
- Analytical parameter-shift gradients
- Exact Fubini-Study metric tensor (Full and Block-Diagonal covariance approximations)

NOTE: All quantum circuits are SIMULATED on classical computers using PennyLane default.qubit.
No quantum hardware is used.
"""

from __future__ import annotations

from typing import Any, Callable, List, Optional, Tuple, Union
import numpy as np
import pennylane as qml
from scipy.linalg import block_diag


def ising_chain_hamiltonian(n: int, J: float = 1.0, h: float = 1.0) -> qml.Hamiltonian:
    """Build the transverse-field Ising chain Hamiltonian with open boundary conditions:
    H = -J * sum_{i=0}^{n-2} Z_i Z_{i+1} - h * sum_{i=0}^{n-1} X_i.
    """
    if n < 1:
        raise ValueError(f"Number of qubits must be >= 1, got {n}.")

    coeffs: List[float] = []
    obs: List[qml.operation.Observable] = []

    # ZZ interactions
    for i in range(n - 1):
        coeffs.append(-float(J))
        obs.append(qml.PauliZ(i) @ qml.PauliZ(i + 1))

    # Transverse X fields
    for i in range(n):
        coeffs.append(-float(h))
        obs.append(qml.PauliX(i))

    return qml.Hamiltonian(coeffs, obs)


def heisenberg_chain_hamiltonian(n: int) -> qml.Hamiltonian:
    """Build the isotropic Heisenberg (XXX) spin-1/2 chain with open boundary conditions:
    H = sum_{i=0}^{n-2} (X_i X_{i+1} + Y_i Y_{i+1} + Z_i Z_{i+1}).
    """
    if n < 2:
        raise ValueError(f"Heisenberg chain requires at least 2 qubits, got {n}.")

    coeffs: List[float] = []
    obs: List[qml.operation.Observable] = []

    for i in range(n - 1):
        coeffs.extend([1.0, 1.0, 1.0])
        obs.extend([
            qml.PauliX(i) @ qml.PauliX(i + 1),
            qml.PauliY(i) @ qml.PauliY(i + 1),
            qml.PauliZ(i) @ qml.PauliZ(i + 1),
        ])

    return qml.Hamiltonian(coeffs, obs)


def exact_ground_energy(H: qml.Hamiltonian, n: int) -> float:
    """Compute the exact ground-state energy E_0 by diagonalizing the dense Hamiltonian matrix."""
    if n < 1:
        raise ValueError(f"n must be >= 1, got {n}.")
    dense = qml.matrix(H, wire_order=list(range(n)))
    eigenvalues = np.linalg.eigvalsh(dense)
    return float(eigenvalues[0])


def ansatz_param_count(n: int, layers: int) -> int:
    """Return the total number of trainable parameters for the hardware-efficient ansatz:
    2 parameters (RY, RZ) per qubit per layer -> 2 * n * layers.
    """
    if n < 1 or layers < 1:
        raise ValueError(f"n and layers must be >= 1, got n={n}, layers={layers}.")
    return 2 * n * layers


def hardware_efficient_ansatz(params: Any, n: int, layers: int) -> None:
    """Apply the hardware-efficient ansatz circuit:
    For each layer l = 0 ... layers-1:
      - RY(theta) and RZ(theta) on each qubit i = 0 ... n-1
      - Linear entangling ladder of CNOT(i, i+1) for i = 0 ... n-2
    """
    expected_len = ansatz_param_count(n, layers)
    if len(params) != expected_len:
        raise ValueError(f"Expected {expected_len} parameters for n={n}, layers={layers}, got {len(params)}.")

    idx = 0
    for l in range(layers):
        for i in range(n):
            qml.RY(params[idx], wires=i)
            idx += 1
            qml.RZ(params[idx], wires=i)
            idx += 1
        for i in range(n - 1):
            qml.CNOT(wires=[i, i + 1])


def make_vqe_qnode(
    H: qml.Hamiltonian,
    n: int,
    layers: int,
    dev: Optional[qml.Device] = None,
) -> Callable[[np.ndarray], float]:
    """Create and return a PennyLane QNode computing <psi(params)| H |psi(params)>."""
    if dev is None:
        dev = qml.device("default.qubit", wires=n)

    @qml.qnode(dev, interface="autograd")
    def qnode(params: np.ndarray):
        hardware_efficient_ansatz(params, n, layers)
        return qml.expval(H)

    return qnode


def make_state_qnode(
    n: int,
    layers: int,
    dev: Optional[qml.Device] = None,
) -> Callable[[np.ndarray], np.ndarray]:
    """Create and return a PennyLane QNode returning the final statevector."""
    if dev is None:
        dev = qml.device("default.qubit", wires=n)

    @qml.qnode(dev, interface="autograd")
    def qnode(params: np.ndarray):
        hardware_efficient_ansatz(params, n, layers)
        return qml.state()

    return qnode


def param_shift_grad_vqe(
    energy_qnode: Callable[[np.ndarray], float],
    params: np.ndarray,
) -> np.ndarray:
    """Compute the analytical gradient of the energy w.r.t parameters using the parameter-shift rule.
    Since every parameter drives a single-qubit rotation (RY or RZ) generated by Pauli operators with
    eigenvalues +- 1/2, a shift of pi/2 on each parameter yields the exact gradient:
    dE/dtheta_i = (E(theta + pi/2 e_i) - E(theta - pi/2 e_i)) / 2.
    """
    p = np.asarray(params, dtype=float).copy()
    d = len(p)
    grad = np.zeros(d, dtype=np.float64)
    shift = np.pi / 2.0

    for i in range(d):
        p_plus = p.copy()
        p_plus[i] += shift
        p_minus = p.copy()
        p_minus[i] -= shift
        e_plus = float(energy_qnode(p_plus))
        e_minus = float(energy_qnode(p_minus))
        grad[i] = (e_plus - e_minus) / 2.0

    return grad


def metric_tensor_vqe(
    params: np.ndarray,
    n: int,
    layers: int,
    approx: Optional[str] = None,
    dev_state: Optional[qml.Device] = None,
) -> np.ndarray:
    """Compute the Fubini-Study metric tensor g(theta) of the hardware-efficient ansatz.

    Parameters:
        params: 1D parameter array of length 2 * n * layers.
        n: Number of qubits.
        layers: Number of ansatz layers.
        approx: None for full metric tensor; "block-diag" for block-diagonal covariance approximation.
        dev_state: Optional PennyLane device.

    Returns:
        g: 2D array of shape (d, d) where d = 2 * n * layers.
    """
    if approx not in (None, "block-diag"):
        raise ValueError(f"approx must be None or 'block-diag', got {approx}.")

    p = np.asarray(params, dtype=float).copy()
    d = ansatz_param_count(n, layers)
    if len(p) != d:
        raise ValueError(f"Expected {d} parameters, got {len(p)}.")

    if dev_state is None:
        dev_state = qml.device("default.qubit", wires=n)

    state_qnode = make_state_qnode(n, layers, dev=dev_state)

    if approx is None:
        # Full metric tensor from state derivatives:
        # d_i |psi> = 0.5 * |psi(theta + pi e_i)>
        # g_{ij} = Re(<d_i psi|d_j psi> - <d_i psi|psi><psi|d_j psi>)
        psi = state_qnode(p)
        dpsi_list: List[np.ndarray] = []
        for i in range(d):
            p_shift = p.copy()
            p_shift[i] += np.pi
            dpsi = 0.5 * state_qnode(p_shift)
            dpsi_list.append(dpsi)

        g = np.zeros((d, d), dtype=np.float64)
        for i in range(d):
            for j in range(i, d):
                term1 = np.vdot(dpsi_list[i], dpsi_list[j])
                term2 = np.vdot(dpsi_list[i], psi) * np.vdot(psi, dpsi_list[j])
                val = float(np.real(term1 - term2))
                g[i, j] = val
                g[j, i] = val
        return g

    elif approx == "block-diag":
        # Block-diagonal approximation via generator covariance matrices:
        # Trace the circuit DAG using tape.graph.iterate_parametrized_layers()
        def circuit_builder(p_in):
            hardware_efficient_ansatz(p_in, n, layers)

        tape = qml.tape.make_qscript(circuit_builder)(p)
        blocks = []

        for queue, curr_ops, param_idx, _ in tape.graph.iterate_parametrized_layers():
            @qml.qnode(dev_state)
            def q_sub():
                for op in queue:
                    qml.apply(op)
                return qml.state()

            psi_pre = q_sub()
            m = len(curr_ops)
            cov = np.zeros((m, m), dtype=np.float64)
            gen_mats = [qml.matrix(op.generator(), wire_order=list(range(n))) for op in curr_ops]

            for a in range(m):
                for b in range(a, m):
                    exp_ab = float(np.real(np.vdot(psi_pre, gen_mats[a] @ gen_mats[b] @ psi_pre)))
                    exp_a = float(np.real(np.vdot(psi_pre, gen_mats[a] @ psi_pre)))
                    exp_b = float(np.real(np.vdot(psi_pre, gen_mats[b] @ psi_pre)))
                    val = exp_ab - exp_a * exp_b
                    cov[a, b] = val
                    cov[b, a] = val

            blocks.append(cov)

        if not blocks:
            return np.zeros((d, d), dtype=np.float64)

        return np.asarray(block_diag(*blocks), dtype=np.float64)
